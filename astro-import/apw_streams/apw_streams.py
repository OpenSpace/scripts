#!/usr/bin/env python
"""Convert Adrian Price-Whelan's Milky Way stellar streams data into an OpenSpace asset.

Successor to jupyter-notebooks/mwstreams/MilkyWayStreams.ipynb. Downloads
data.json (or reads a local copy) and writes one .csv file per stream plus a
single mwstreams.asset (RenderablePointCloud nodes) into the output directory.
Loading the asset into OpenSpace is left to the user (or the openspace skill).

Usage:
    python apw_streams.py                    # download + generate into ./output
    python apw_streams.py --input data.json  # use a local copy
"""
import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

DEFAULT_URL = "https://adrian.pw/visualizations/mwstreams/data.json"
HERE = Path(__file__).resolve().parent
ASSET_NAME = "mwstreams.asset"
PAPER_TITLE = "Stellar Streams in the Gaia Era"
PAPER_AUTHORS = "Ana Bonaca and Adrian M. Price-Whelan"
PAPER_CITATION = (
    f"Bonaca & Price-Whelan (2025), {PAPER_TITLE}, New Astronomy Reviews, 100, 101713"
)
PAPER_URL = "https://doi.org/10.48550/arXiv.2405.19410"
VIS_URL = "https://adrian.pw/visualizations/mwstreams/"
REPO_URL = "https://github.com/abonaca/streams_overview"
# Upstream catalogs that streams in the compilation are drawn from. Add more as they are
# identified.
UPSTREAM_SOURCES = [
    "Ibata et al. (2024), Charting the Galactic Acceleration Field. II. A Global Mass "
    "Model of the Milky Way from the STREAMFINDER Atlas of Stellar Streams Detected in "
    "Gaia DR3, The Astrophysical Journal, 967, 89 (https://doi.org/10.3847/1538-4357/ad382d, "
    "arXiv:2311.17202)",
]
ID_PREFIX = "MilkyWayStreams"
GUI_PATH = "/Milky Way/Streams"
# The center of the Milky Way is ~8 kpc from the Sun, along +x in galactic coordinates.
GC_DISTANCE_M = 8 * 3.086e19
DISK_KEY = "Disk"
# Never touched by the toggle action; these stay off unless the user enables them.
EXCLUDED_FROM_TOGGLE = {"Disk", "MClouds"}
DEFAULT_SIZE = 0.35
DISK_SIZE = 0.1
# Streams in the source data use size 0.2 as the typical value; this maps it to a
# SizeSettings.ScaleFactor of 1.0.
REFERENCE_SIZE = 0.2


def load_streams(input_path, url):
    if input_path:
        with open(input_path, encoding="utf8") as f:
            return json.load(f)
    print(f"Downloading {url}")
    with urllib.request.urlopen(url, timeout=120) as resp:
        return json.loads(resp.read().decode())


def clean_name(key):
    """'ATLAS-Aliqa Uma' -> 'ATLASAliqaUma' (safe for file names and identifiers)."""
    return re.sub(r"[^A-Za-z0-9]", "", key)


def hex_to_rgb(color):
    n = int(color, 16)
    return ((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_csv(path, points):
    with open(path, "w", newline="\n") as f:
        f.write("x,y,z\n")
        for x, y, z in points:
            f.write(f"{x},{y},{z}\n")


def node_lua(ident, display, csv_name, rgb, opacity, size):
    return f"""  {{
    Identifier = {lua_str(ident)},
    Parent = "Root",
    Transform = {{
      Translation = {{
        Type = "StaticTranslation",
        Position = {{ GalacticCenterDistance, 0, 0 }}
      }}
    }},
    Renderable = {{
      Type = "RenderablePointCloud",
      Enabled = false,
      Opacity = {opacity},
      File = asset.resource({lua_str(csv_name)}),
      Unit = "Kpc",
      Coloring = {{
        FixedColor = {{ {rgb[0]:.4f}, {rgb[1]:.4f}, {rgb[2]:.4f} }}
      }},
      SizeSettings = {{
        ScaleFactor = {size / REFERENCE_SIZE:g}
      }}
    }},
    GUI = {{
      Name = {lua_str(display)},
      Path = {lua_str(GUI_PATH)}
    }}
  }},
"""


def build(streams, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)

    nodes, toggled_ids, seen = [], [], set()
    for key, stream in streams.items():
        name = clean_name(key)
        if not name or name in seen:
            print(f"  skipping {key!r}: empty or duplicate identifier {name!r}")
            continue
        seen.add(name)

        write_csv(out_dir / f"{name}.csv", stream["data"])
        size = stream.get("size", DISK_SIZE if key == DISK_KEY else DEFAULT_SIZE)
        nodes.append(node_lua(
            ID_PREFIX + name, key, f"{name}.csv",
            hex_to_rgb(stream["color"]), stream.get("opacity", 1.0), size,
        ))
        if key not in EXCLUDED_FROM_TOGGLE:
            toggled_ids.append(ID_PREFIX + name)
        print(f"  {key:<20} {len(stream['data']):>7} points")

    ids_lua = ", ".join(lua_str(i) for i in toggled_ids)
    upstream_comment = "".join(f"--   * {c}{chr(10)}" for c in UPSTREAM_SOURCES)
    asset = f"""-- Generated by apw_streams.py from {DEFAULT_URL}
--
-- Stream data: compiled in {PAPER_CITATION}
-- ({PAPER_URL}) and
-- provided by Adrian Price-Whelan for the Milky Way stellar streams visualization at
-- {VIS_URL}
-- Compilation data and notebooks: {REPO_URL}
--
-- The compilation includes streams from these upstream catalogs (more to be added):
{upstream_comment}
asset.meta = {{
  Name = "Milky Way Stellar Streams",
  Description = [[Stellar streams of the Milky Way, as compiled in {PAPER_CITATION}. Positions
    come from the data provided with Adrian Price-Whelan's stellar streams visualization
    ({VIS_URL}); compilation data at {REPO_URL}.
    Disk and Magellanic Clouds are off by default; the toggle action shows or hides the
    streams.]],
  Author = {lua_str(PAPER_AUTHORS)},
  URL = {lua_str(PAPER_URL)}
}}

local GalacticCenterDistance = {GC_DISTANCE_M:.6g}

local nodes = {{
{''.join(nodes)}}}

-- Exporting registers each node's identifier with this asset's meta information
for _, node in ipairs(nodes) do
  asset.export(node)
end

local toggleStreamsAction = {{
  Identifier = "toggleStreams",
  Name = "Toggle Milky Way Stream Visibility",
  Command = [[
    local ids = {{ {ids_lua} }}
    local show = not openspace.propertyValue("Scene." .. ids[1] .. ".Renderable.Enabled")
    for _, id in ipairs(ids) do
      local uri = "Scene." .. id .. ".Renderable"
      if show then
        openspace.setPropertyValue(uri .. ".Fade", 0)
        openspace.setPropertyValue(uri .. ".Enabled", true)
        openspace.setPropertyValue(uri .. ".Fade", 1, 3, "CubicEaseOut")
      else
        openspace.setPropertyValue(uri .. ".Fade", 0, 3, "CubicEaseOut",
          "openspace.setPropertyValue('" .. uri .. ".Enabled', false)")
      end
    end
  ]],
  GuiPath = {lua_str(GUI_PATH)},
  IsLocal = true
}}

asset.onInitialize(function()
  openspace.action.registerAction(toggleStreamsAction)
  for _, node in ipairs(nodes) do
    openspace.addSceneGraphNode(node)
  end
end)

asset.onDeinitialize(function()
  openspace.action.removeAction(toggleStreamsAction)
  for _, node in ipairs(nodes) do
    openspace.removeSceneGraphNode(node.Identifier)
  end
end)
"""
    asset_path = out_dir / ASSET_NAME
    asset_path.write_text(asset, encoding="utf8")
    print(f"Wrote {len(nodes)} streams and {asset_path}")
    return asset_path


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--input", help="local data.json to use instead of downloading")
    p.add_argument("--url", default=DEFAULT_URL, help="data.json URL (default: %(default)s)")
    p.add_argument("--output", type=Path, default=HERE / "output", help="output directory (default: ./output)")
    args = p.parse_args()

    build(load_streams(args.input, args.url), args.output)


if __name__ == "__main__":
    sys.exit(main())
