GROUP_TEMPLATE = """\
-- {group_name}: generated by scale-objects/generate.py ({style_name} style).
-- Regenerate rather than editing by hand; boundaries from {attribution}.
-- All the node and action logic lives in scale_locations.asset; this is just data.
local earthAsset = asset.require("scene/solarsystem/planets/earth/globe")
local sunAsset = asset.require("scene/solarsystem/sun/transforms")
local locations = asset.require("{shared}")


local Regions = locations.createRegions({{
  Prefix = {prefix},
  GuiPath = {gui_path},
  Globe = earthAsset.Earth.Identifier,
  LightSource = sunAsset.LightSource,
  ReferenceRadius = {reference_radius},
  StartEnabled = {start_enabled},
  Resource = function(file) return asset.resource("models/" .. file) end,
  Parts = {{
    Fill = {fill},
    Grid = {grid},
    Outline = {outline}
  }},
  Regions = {{
{regions}
  }}
}})


asset.onInitialize(function()
  locations.addRegions(Regions)
end)

asset.onDeinitialize(function()
  locations.removeRegions(Regions)
end)


""" + META

SET_TEMPLATE = """-- {set_title}: loads every group of the set. Generated by scale-objects/generate.py.
-- Loading this together with one of its groups is fine: each group is loaded once.
{requires}


""" + META


def write_shared_asset(out_root: Path) -> None:
    """Copy the hand-written shared asset next to the generated sets."""
    shutil.copyfile(LUA_DIR / SHARED_ASSET, out_root / SHARED_ASSET)


def write_license(out_root: Path, sources) -> None:
    """LICENSE.md at the top of the output: the code's license plus, for every source,
    where its boundaries come from and their terms."""
    lines = [
        "# Scale locations: licenses",
        "",
        "The OpenSpace assets (`*.asset`) are released under the MIT license, like",
        "OpenSpace itself. The models (`*/models/*.glb`) are derived from the public",
        "domain boundary data below and can be used without restriction.",
        "",
        "## Boundary data",
    ]
    for s in sources:
        lines += [
            "",
            f"### {s.title} (`{s.folder}/`)",
            "",
            f"- Source: {s.attribution}",
            f"- Download: {s.url}",
            f"- Terms: {s.license}",
        ]
    (out_root / "LICENSE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_group_asset(
    path: Path,
    *,
    prefix: str,
    group_name: str,
    gui_path: str,
    style: Style,
    regions: list[RegionEntry],
    attribution: str,
    reference_radius: float,
    start_enabled: bool = False,
    shared: str = "../scale_locations",
) -> None:
    rows = [
        "    " + _lua({
            "Key": r.key,
            "Name": r.name,
            "Latitude": r.latitude,
            "Longitude": r.longitude,
            "Description": region_description(r.name, r.area_km2, r.note),
            "Models": r.models,
        })
        for r in regions
    ]
    names = ", ".join(r.name for r in regions)
    text = GROUP_TEMPLATE.format(
        group_name=group_name,
        style_name=style.name,
        attribution=attribution,
        shared=shared,
        prefix=_lua(prefix),
        gui_path=_lua(gui_path),
        reference_radius=_lua(reference_radius),
        start_enabled=_lua(start_enabled),
        fill=_lua(_part_settings(style.fill)),
        grid=_lua(_part_settings(style.grid)),
        outline=_lua(_part_settings(style.outline)),
        regions=",\n".join(rows),
        name=_lua(f"Scale Locations - {group_name}"),
        description=_lua(
            f"True-scale outlines of {names}, curved to match whichever globe they are "
            "placed on. Hidden by default; use the actions to place one under the camera "
            f"or at its real location. Boundaries: {attribution}."
        ),
    )
    path.write_text(text, encoding="utf-8")


def write_set_asset(
    path: Path,
    *,
    set_title: str,
    groups: list[tuple[str, str]],  # (asset file stem, group name)
    attribution: str,
) -> None:
    requires = "\n".join(f'asset.require("./{stem}")' for stem, _ in groups)
    text = SET_TEMPLATE.format(
        set_title=set_title,
        requires=requires,
        name=_lua(f"Scale Locations - {set_title}"),
        description=_lua(
            f"All {set_title} as true-scale outlines ("
            + ", ".join(name for _, name in groups)
            + f"). Boundaries: {attribution}."
        ),
    )
    path.write_text(text, encoding="utf-8")
